static uint16_t expand_8_to_16(uint8_t v)
{
    uint16_t out = 0U;
    uint8_t i;

    for (i = 0U; i < 8U; ++i) {
        if ((v & (1U << i)) != 0U) {
            out |= (uint16_t)(0x3U << (2U * i));
        }
    }
    return out;
}

void OLED_Clear(void)
{
    uint8_t zeros[128] = {0};
    uint8_t page;
    for (page = 0; page < 8U; ++page) {
        OLED_SetPos(page, 0);
        OLED_WriteData(zeros, sizeof(zeros));
    }
}

static void OLED_PutChar(uint8_t page, uint8_t col, char c)
{
    uint8_t idx;
    uint8_t space = 0x00;

    if ((c < 32) || (c > 126)) {
        c = '?';
    }

    idx = (uint8_t)(c - 32);
    OLED_SetPos(page, col);
    OLED_WriteData(Font5x7[idx], 5);
    OLED_WriteData(&space, 1);
}

static void OLED_PutCharMedium(uint8_t page, uint8_t col, char c)
{
    uint8_t idx;
    uint8_t src_col;
    uint16_t col_bits;
    uint8_t top[16];
    uint8_t bottom[16];
    uint8_t x;

    if ((c < 32) || (c > 126)) {
        c = '?';
    }

    idx = (uint8_t)(c - 32);

    for (x = 0U; x < 16U; ++x) {
        top[x] = 0x00;
        bottom[x] = 0x00;
    }

    for (src_col = 0U; src_col < 5U; ++src_col) {
        col_bits = expand_8_to_16(Font5x7[idx][src_col]);

        x = (uint8_t)(src_col * 2U);
        top[x] = (uint8_t)(col_bits & 0xFFU);
        top[(uint8_t)(x + 1U)] = (uint8_t)(col_bits & 0xFFU);
        bottom[x] = (uint8_t)((col_bits >> 8) & 0xFFU);
        bottom[(uint8_t)(x + 1U)] = (uint8_t)((col_bits >> 8) & 0xFFU);
    }

    OLED_SetPos(page, col);
    OLED_WriteData(top, sizeof(top));
    OLED_SetPos((uint8_t)(page + 1U), col);
    OLED_WriteData(bottom, sizeof(bottom));
}

void OLED_Print(uint8_t page, uint8_t col, const char *s)
{
    OLED_PrintEx(page, col, s, OLED_FONT_SMALL_5X7);
}

void OLED_PrintEx(uint8_t page, uint8_t col, const char *s, oled_font_t font)
{
    if (s == NULL) {
        return;
    }

    while (*s != '\0') {
        if (font == OLED_FONT_MEDIUM_8X16) {
            if (page > 6U) {
                break;
            }
            OLED_PutCharMedium(page, col, *s);
            col = (uint8_t)(col + 12U);
            if (col > 116U) {
                break;
            }
        } else {
            OLED_PutChar(page, col, *s);
            col = (uint8_t)(col + 6U);
            if (col > 122U) {
                break;
            }
        }
        ++s;
    }
}

static void delay_ms(uint32_t ms)
{
    uint32_t i;
    for (i = 0; i < (ms * 1000U); ++i) {
        __NOP();
    }
}
