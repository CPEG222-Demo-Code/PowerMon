static inline void OLED_Select(void) { SPI1_PORT->ODR &= ~(1U << SPI1_CS_PIN); }
static inline void OLED_Unselect(void) { SPI1_PORT->ODR |= (1U << SPI1_CS_PIN); }
static inline void OLED_DC_Cmd(void) { OLED_PORT->ODR &= ~(1U << OLED_DC_PIN); }
static inline void OLED_DC_Data(void) { OLED_PORT->ODR |= (1U << OLED_DC_PIN); }
static inline void RES_Low(void) { OLED_PORT->ODR &= ~(1U << OLED_RESET_PIN); }
static inline void RES_High(void) { OLED_PORT->ODR |= (1U << OLED_RESET_PIN); }

static inline void SPI_WriteByte(uint8_t data)
{
    while (!(SPI1->SR & SPI_SR_TXE));
    SPI1->DR = data;
    while (!(SPI1->SR & SPI_SR_TXE));
    while (SPI1->SR & SPI_SR_BSY);
}

static void SPI_Write(const uint8_t *buf, size_t len)
{
    size_t i;
    for (i = 0; i < len; ++i) {
        SPI_WriteByte(buf[i]);
    }
}

static void OLED_WriteCmd(uint8_t cmd)
{
    OLED_Select();
    OLED_DC_Cmd();
    SPI_WriteByte(cmd);
    OLED_Unselect();
}

static void OLED_WriteData(const uint8_t *buf, size_t len)
{
    OLED_Select();
    OLED_DC_Data();
    SPI_Write(buf, len);
    OLED_Unselect();
}

void OLED_Init(void)
{
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOAEN;
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOGEN;

    SPI1_PORT->MODER &= ~((0x3U << (SPI1_SCK_PIN * 2U)) |
                          (0x3U << (SPI1_MISO_PIN * 2U)) |
                          (0x3U << (SPI1_MOSI_PIN * 2U)) |
                          (0x3U << (SPI1_CS_PIN * 2U)));
    SPI1_PORT->MODER |= (0x2U << (SPI1_SCK_PIN * 2U)) |
                        (0x2U << (SPI1_MISO_PIN * 2U)) |
                        (0x2U << (SPI1_MOSI_PIN * 2U)) |
                        (0x1U << (SPI1_CS_PIN * 2U));

    SPI1_PORT->AFR[0] &= ~((0xFU << (SPI1_SCK_PIN * 4U)) |
                           (0xFU << (SPI1_MISO_PIN * 4U)) |
                           (0xFU << (SPI1_MOSI_PIN * 4U)));
    SPI1_PORT->AFR[0] |= (5U << (SPI1_SCK_PIN * 4U)) |
                         (5U << (SPI1_MISO_PIN * 4U)) |
                         (5U << (SPI1_MOSI_PIN * 4U));

    SPI1_PORT->OSPEEDR |= (0x3U << (SPI1_SCK_PIN * 2U)) |
                          (0x3U << (SPI1_MOSI_PIN * 2U));

    OLED_PORT->MODER &= ~((0x3U << (OLED_DC_PIN * 2U)) |
                          (0x3U << (OLED_RESET_PIN * 2U)));
    OLED_PORT->MODER |= (0x1U << (OLED_DC_PIN * 2U)) |
                        (0x1U << (OLED_RESET_PIN * 2U));

    OLED_Unselect();
    OLED_DC_Data();
    RES_High();

    RCC->APB2ENR |= RCC_APB2ENR_SPI1EN;
    SPI1->CR1 = SPI_CR1_MSTR | SPI_CR1_SSM | SPI_CR1_SSI | SPI_CR1_BR_2 | SPI_CR1_BR_1;
    SPI1->CR2 = 0;
    SPI1->CR1 |= SPI_CR1_SPE;

    RES_Low();
    delay_ms(10);
    RES_High();
    delay_ms(10);

    OLED_WriteCmd(0xAE);
    OLED_WriteCmd(0xD5); OLED_WriteCmd(0x80);
    OLED_WriteCmd(0xA8); OLED_WriteCmd(0x3F);
    OLED_WriteCmd(0xD3); OLED_WriteCmd(0x00);
    OLED_WriteCmd(0x40);
    OLED_WriteCmd(0xAD); OLED_WriteCmd(0x8B);
    OLED_WriteCmd(0xA1);
    OLED_WriteCmd(0xC8);
    OLED_WriteCmd(0xDA); OLED_WriteCmd(0x12);
    OLED_WriteCmd(0x81); OLED_WriteCmd(0x7F);
    OLED_WriteCmd(0xD9); OLED_WriteCmd(0x22);
    OLED_WriteCmd(0xDB); OLED_WriteCmd(0x20);
    OLED_WriteCmd(0xA4);
    OLED_WriteCmd(0xA6);
    OLED_WriteCmd(0xAF);

    OLED_Clear();
}

static void OLED_SetPos(uint8_t page, uint8_t col)
{
    uint8_t x = (uint8_t)(col + 2U);
    OLED_WriteCmd((uint8_t)(0xB0U | (page & 0x0FU)));
    OLED_WriteCmd((uint8_t)(0x00U | (x & 0x0FU)));
    OLED_WriteCmd((uint8_t)(0x10U | ((x >> 4) & 0x0FU)));
}

