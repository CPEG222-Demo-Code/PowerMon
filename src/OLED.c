#define SPI1_SCK_PIN     5U
#define SPI1_MISO_PIN    6U
#define SPI1_MOSI_PIN    7U
#define SPI1_CS_PIN      15U
#define SPI1_PORT        GPIOA
#define OLED_DC_PIN      2U
#define OLED_RESET_PIN   3U
#define OLED_PORT        GPIOG

